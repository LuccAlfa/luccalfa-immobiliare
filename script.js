// --- Language Switcher Logic ---
let currentLang = 'it';

document.addEventListener('DOMContentLoaded', () => {
  const langBtn = document.getElementById('lang-toggle');
  
  if (langBtn) {
    langBtn.addEventListener('click', () => {
      currentLang = currentLang === 'it' ? 'en' : 'it';
      
      // Update toggle button icon and text
      if (currentLang === 'en') {
        langBtn.innerHTML = `<svg class="flag-icon" width="20" height="20"><use href="#flag-it"/></svg><span class="lang-code">IT</span>`;
      } else {
        langBtn.innerHTML = `<svg class="flag-icon" width="20" height="20"><use href="#flag-gb"/></svg><span class="lang-code">EN</span>`;
      }

      // Update HTML lang attribute
      document.documentElement.lang = currentLang;

      // Translate all data-i18n elements
      document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[currentLang] && translations[currentLang][key]) {
          el.textContent = translations[currentLang][key];
        }
      });
    });
  }

  // --- Sample Listing Data & Filtering ---
  const LISTINGS = [
    { id: 1, title: 'Appartamento dentro le Mura', price: '€ 320.000', type: 'vendita', area: 'Lucca Centro', beds: 2, baths: 1 },
    { id: 2, title: 'Casale panoramico con uliveto', price: '€ 650.000', type: 'vendita', area: 'Colline di Lucca', beds: 4, baths: 3 },
    { id: 3, title: 'Attico moderno con terrazzo', price: '€ 1.200 / mese', type: 'affitto', area: 'Pisa Center', beds: 2, baths: 2 }
  ];

  const grid = document.getElementById('listings-grid');
  function renderListings(filter = 'all') {
    if (!grid) return;
    grid.innerHTML = '';
    
    const items = filter === 'all' ? LISTINGS : LISTINGS.filter(item => item.type === filter);
    
    items.forEach(item => {
      const el = document.createElement('div');
      el.className = 'card liquid-glass listing-card';
      el.innerHTML = `
        <h3>${item.title}</h3>
        <p><strong>${item.price}</strong> - ${item.area}</p>
        <small>${item.beds} camere · ${item.baths} bagni</small>
      `;
      grid.appendChild(el);
    });
  }

  renderListings();

  document.querySelectorAll('.tab-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      document.querySelectorAll('.tab-btn').forEach(b => b.classList.remove('active'));
      e.target.classList.add('active');
      renderListings(e.target.getAttribute('data-filter'));
    });
  });
});
